import { execFile } from 'node:child_process';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { promisify } from 'node:util';
import { join } from 'node:path';
import { cloneWithInstallationToken, pushBranchWithInstallationToken } from './clone.mjs';
import { safeBranch, safeProjectName } from './security.mjs';

const exec = promisify(execFile);
// `ryoko-fix` is the label operators add to an issue; `ryoko:agent` is the older
// spelling and keeps existing installations working.
const AGENT_LABELS = ['ryoko-fix', 'ryoko:agent'];
const AGENT_LABEL = AGENT_LABELS[0];
const MAX_GOAL = 12_000;
const MAX_PR_BODY = 12_000;
const MAX_ATTACHMENT = 9_000;

const bad = (message, status = 400) => Object.assign(new Error(message), { status });

function text(value, limit) {
  return String(value == null ? '' : value).replace(/\0/g, '').slice(0, limit);
}

/**
 * Returns a normalized pipeline request only for a human-applied agent label.
 * The caller must still verify webhook signatures and repository allowlists.
 */
export function normalizeIssueRequest(payload) {
  if (!payload || typeof payload !== 'object' || payload.issue?.pull_request) return null;
  const installationId = Number(payload.installation?.id);
  const repoId = Number(payload.repository?.id);
  const number = Number(payload.issue?.number);
  const fullName = String(payload.repository?.full_name || '');
  const [owner, name, extra] = fullName.split('/');
  if (!Number.isSafeInteger(installationId) || installationId <= 0
    || !Number.isSafeInteger(repoId) || repoId <= 0
    || !Number.isSafeInteger(number) || number <= 0
    || extra !== undefined
    || !/^[A-Za-z0-9_.-]+$/.test(owner || '') || !/^[A-Za-z0-9_.-]+$/.test(name || '')
    || ['.', '..'].includes(owner) || ['.', '..'].includes(name)) {
    return null;
  }
  const title = text(payload.issue?.title, 180).trim();
  if (!title) return null;
  return {
    installationId,
    repoId,
    owner,
    name,
    fullName,
    number,
    title,
    body: text(payload.issue?.body, MAX_GOAL),
    defaultBranch: text(payload.repository?.default_branch, 120) || 'main',
  };
}

/** Only the exact newly applied agent label authorizes a label-triggered run. */
export function issueAgentRequest(event, payload) {
  if (event !== 'issues' || payload?.action !== 'labeled') return null;
  if (!AGENT_LABELS.includes(payload.label?.name)) return null;
  if (!Array.isArray(payload.issue?.labels)
    || !payload.issue.labels.some((label) => label?.name === payload.label.name)
    || payload.issue?.state === 'closed') return null;
  return normalizeIssueRequest(payload);
}

/**
 * Pulls the pre-merge security audit out of the validation logs the CLI emits.
 * The audit runs inside the container-backed pre-flight check, so its findings
 * arrive as `security audit: ...` lines rather than a separate report field.
 */
export function securityAuditLines(report) {
  const prefix = 'security audit:';
  const lines = [];
  for (const entry of Array.isArray(report?.validation) ? report.validation : []) {
    for (const log of Array.isArray(entry?.logs) ? entry.logs : []) {
      const line = String(log == null ? '' : log);
      if (line.startsWith(prefix)) lines.push(line.slice(prefix.length).trim());
    }
  }
  return lines; // bounded by the validation log cap, then by the body cut below
}

export function buildPullRequestBody(issue, report) {
  const ledger = JSON.stringify(report?.ledger || {}, null, 2).slice(0, MAX_ATTACHMENT);
  const validation = JSON.stringify(report?.validation || [], null, 2).slice(0, MAX_ATTACHMENT);
  const audit = securityAuditLines(report).slice(0, 40).join('\n').slice(0, MAX_ATTACHMENT);
  const body = [
    `Closes #${issue.number}`,
    '',
    `Generated by Ryoko for: ${issue.title}`,
    '',
    'This draft was produced by the multi-agent DAG in an isolated worktree. Review the diff and validation evidence before merging.',
    '',
    '## Token ledger',
    '',
    '```json',
    ledger,
    '```',
    '',
    '## Security audit',
    '',
    '```text',
    audit || 'no security audit output was recorded for this run',
    '```',
    '',
    '## Validation report',
    '',
    '```json',
    validation,
    '```',
  ].join('\n');
  return body.slice(0, MAX_PR_BODY);
}

/**
 * Team jobs publish several role-specific branches. The first success is
 * typically Architect, not the merged deliverable; only Integrator is safe
 * to present as the single combined PR. Never publish a partial/failed DAG.
 */
export function selectIntegratedSuccess(report) {
  const run = report?.run;
  if (!run || !Array.isArray(run.succeeded)
    || (Array.isArray(run.failed) && run.failed.length > 0)
    || (Array.isArray(run.skipped) && run.skipped.length > 0)
    || (Array.isArray(run.needs_human_review) && run.needs_human_review.length > 0)) {
    throw bad('Ryoko team run is incomplete or needs human review', 502);
  }
  const integrators = run.succeeded.filter(
    (item) => item?.role === 'integrator' && typeof item.branch === 'string' && item.branch,
  );
  if (integrators.length !== 1) {
    throw bad('Ryoko produced no unique integrated branch', 502);
  }
  return integrators[0];
}

const MCP_FLAGS = [
  ['server', '--mcp-server'],
  ['serverArgs', '--mcp-server-arg'],
  ['allowEnv', '--mcp-allow-env'],
  ['allowTools', '--mcp-allow-tool'],
  ['headlessApprove', '--mcp-headless-approve'],
];

/**
 * Builds the `ryoko run` argv. MCP settings are operator configuration, so they
 * are forwarded verbatim as separate argv entries - never through a shell - and a
 * value that looks like a flag is dropped rather than allowed to become one.
 */
export function buildRunArgs({ cwd, goal, reportPath, mcp }) {
  const args = ['run', '--team', '--repo', cwd, '--report', reportPath];
  for (const [key, flag] of MCP_FLAGS) {
    const value = mcp?.[key];
    const values = Array.isArray(value) ? value : value == null ? [] : [value];
    for (const item of values) {
      const text = String(item).trim();
      if (!text || text.startsWith('-')) continue;
      args.push(flag, text);
    }
  }
  if (Number.isSafeInteger(mcp?.maxCalls) && mcp.maxCalls > 0) {
    args.push('--mcp-max-calls', String(mcp.maxCalls));
  }
  args.push(goal);
  return args;
}

async function defaultRunCli({ binary, cwd, goal, reportPath, timeoutMs, mcp }) {
  const args = buildRunArgs({ cwd, goal, reportPath, mcp });
  try {
    await exec(binary, args, {
      cwd, timeout: timeoutMs, maxBuffer: 4_000_000, shell: false,
      env: { ...process.env, RYOKO_NONINTERACTIVE: '1' },
    });
  } catch (error) {
    const report = await stat(reportPath).catch(() => null);
    if (!report?.isFile()) throw error;
  }
}

/**
 * Clones the repository, runs `ryoko run --team`, pushes the published branch,
 * and opens a draft pull request with the ledger and validation evidence.
 */
export async function runIssuePipeline({
  broker,
  request,
  settings,
  clone = cloneWithInstallationToken,
  runCli = defaultRunCli,
  pushBranch = pushBranchWithInstallationToken,
  logger = console,
}) {
  if (!settings?.projectsRoot) throw bad('RYOKO_PROJECTS_ROOT is not configured', 503);
  if (!settings?.ryokoBinary) throw bad('RYOKO_CLI_BIN is not configured', 503);
  if (!Array.isArray(settings.agentRepoIds) || !settings.agentRepoIds.includes(request.repoId)) {
    throw bad('repository is not allowlisted for agent runs', 403);
  }
  const projectName = safeProjectName(
    `${request.name.slice(0, 20)}-${request.number}`.replace(/[^A-Za-z0-9_-]/g, '-').slice(0, 40),
  );
  const cloneToken = await broker.installationToken(request.installationId, request.repoId, 'clone');
  const cloned = await clone({
    repo: { full_name: request.fullName }, token: cloneToken,
    projectsRoot: settings.projectsRoot, projectName,
  });
  const reportPath = join(cloned.path, '.ryoko', 'issue-report.json');
  await mkdir(join(cloned.path, '.ryoko'), { recursive: true, mode: 0o700 });
  const goal = `GitHub issue #${request.number}: ${request.title}\n\n${request.body}`.trim();
  logger.log?.(`Ryoko issue pipeline started for ${request.fullName}#${request.number}`);
  await runCli({
    binary: settings.ryokoBinary,
    cwd: cloned.path,
    goal: goal.slice(0, MAX_GOAL),
    reportPath,
    timeoutMs: settings.pipelineTimeoutMs || 15 * 60_000,
    mcp: settings.mcp || null,
  });
  const report = JSON.parse(await readFile(reportPath, 'utf8'));
  const success = selectIntegratedSuccess(report);
  const branch = safeBranch(success.branch);

  const pushToken = await broker.installationToken(request.installationId, request.repoId, 'contents');
  await pushBranch({ path: cloned.path, branch, token: pushToken });

  const prToken = await broker.installationToken(request.installationId, request.repoId, 'pull_requests');
  const root = `/repos/${encodeURIComponent(request.owner)}/${encodeURIComponent(request.name)}`;
  const created = await broker.request(root + '/pulls', prToken, {
    method: 'POST',
    body: {
      head: branch,
      base: request.defaultBranch,
      title: text(`[ryoko] ${request.title}`, 140),
      body: buildPullRequestBody(request, report),
      draft: true,
    },
  });
  logger.log?.(`Ryoko opened draft PR #${created.number} for ${request.fullName}#${request.number}`);
  return {
    branch,
    number: created.number,
    html_url: created.html_url,
    task_id: success.task_id,
  };
}

